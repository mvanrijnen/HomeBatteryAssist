SETUP_STEPS = ("meter", "direct", "user", "max_current", "sensors")
SUBENTRY_STEP = {"battery": "battery"}  # the form with the fields (else "user")


def cell(value: str) -> str:
    """Text for a table cell."""
    return str(value or "").replace("|", "\\|").replace("\n", " ").strip()


def fields(data: dict, descriptions: dict, t: dict) -> list[str]:
    """A table of the fields of one form."""
    if not data:
        return []
    if not any(descriptions.get(key) for key in data):
        return [", ".join(f"**{cell(label)}**" for label in data.values()), ""]
    rows = [f"| {t['field']} | {t['explanation']} |", "|---|---|"]
    rows += [
        f"| **{cell(label)}** | {cell(descriptions.get(key, ''))} |"
        for key, label in data.items()
    ]
    return [*rows, ""]


def page(lang: str) -> str:
    """The reference page in one language."""
    t = TEXT[lang]
    texts = json.loads((TRANSLATIONS / f"{lang}.json").read_text(encoding="utf-8"))
    out = [f"# {t['title']}", "", t["intro"], ""]

    out += [f"## {t['setup']} {{#setup}}", "", t["setup_intro"], ""]
    for step in SETUP_STEPS:
        form = texts["options"]["step"].get(step) or texts["config"]["step"][step]
        out += [
            f"### {form.get('title', step)} {{#setup-{step.replace('_', '-')}}}",
            "",
        ]
        if form.get("description"):
            out += [cell(form["description"]), ""]
        out += fields(form.get("data", {}), form.get("data_description", {}), t)

    settings = texts["options"]["step"]["settings"]
    out += [f"## {t['settings']} {{#settings}}", "", t["settings_intro"], ""]
    out += [f"### {t['main']} {{#settings-main}}", ""]
    out += fields(settings.get("data", {}), settings.get("data_description", {}), t)
    for key, section in settings.get("sections", {}).items():
        out += [f"### {section['name']} {{#settings-{key.replace('_', '-')}}}", ""]
        if section.get("description"):
            out += [cell(section["description"]), ""]
        out += fields(section.get("data", {}), section.get("data_description", {}), t)

    out += [f"## {t['devices']} {{#devices}}", "", t["devices_intro"], ""]
    for key, sub in texts.get("config_subentries", {}).items():
        step = sub["step"].get(SUBENTRY_STEP.get(key, "user")) or sub["step"]["user"]
        title = sub.get("entry_type") or step.get("title") or key
        out += [f"### {title} {{#device-{key.replace('_', '-')}}}", ""]
        if step.get("description"):
            out += [cell(step["description"]), ""]
        out += fields(step.get("data", {}), step.get("data_description", {}), t)

    out += [f"## {t['entities']} {{#entities}}", "", t["entities_intro"], ""]
    out += [f"| {t['name']} | {t['kind']} |", "|---|---|"]
    for platform, entities in texts.get("entity", {}).items():
        kind = t.get(platform, platform)
        out += [
            f"| {cell(entity.get('name', key))} | {kind} |"
            for key, entity in entities.items()
        ]
    out += [""]

    out += [f"## {t['actions']} {{#actions}}", "", t["actions_intro"], ""]
    for key, service in texts.get("services", {}).items():
        out += [f"### {service['name']} {{#action-{key.replace('_', '-')}}}", ""]
        out += [
            f"`homebatteryassist.{key}` — {cell(service.get('description', ''))}",
            "",
        ]
        service_fields = service.get("fields", {})
        out += fields(
            {k: f.get("name", k) for k, f in service_fields.items()},
            {k: f.get("description", "") for k, f in service_fields.items()},
            t,
        )

    out += ["---", "", f"*{t['generated']}*", ""]
    return "\n".join(out)


def main() -> None:
    for lang, name in (("en", "reference.md"), ("nl", "reference.nl.md")):
        (DOCS / name).write_text(page(lang), encoding="utf-8", newline="\n")
        print(f"docs/{name}")


if __name__ == "__main__":
    main()
