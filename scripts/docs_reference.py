"""Generate the settings reference pages of the documentation site.

Reads the integration's own texts (``translations/en.json`` and
``translations/nl.json``) and writes ``docs/reference.md`` and
``docs/reference.nl.md``: every setup step, setting, device form, entity and
action with the label and explanation the user sees in Home Assistant. So the
reference always matches the screens; run it after changing a text:

    python scripts/docs_reference.py
"""

